import { useEffect, useState } from 'preact/hooks';
import { listPhotos } from '../db.js';
import { buildReportModel } from '../export/model.js';
import { APP_NAME } from '../defaults.js';

/** HTML rendering of the report model – identical structure to PDF/Excel/Word output. */
export function ReportPreview({ project, report }) {
  const [photos, setPhotos] = useState([]);
  useEffect(() => {
    let urls = [];
    listPhotos(report.id).then((list) => {
      const ps = list.filter((p) => !p.excluded).map((p) => { const url = URL.createObjectURL(p.blob); urls.push(url); return { url, width: p.width, height: p.height, caption: p.caption }; });
      setPhotos(ps);
    });
    return () => urls.forEach((u) => URL.revokeObjectURL(u));
  }, [report.id]);
  const m = buildReportModel({ project, report, photos });
  return (
    <div class="preview-wrap print-area">
      <div class="rp">
        {m.logos.length > 0 && <div class="logos" style={m.logos.length === 1 ? { justifyContent: 'flex-start' } : null}>{m.logos.map((l, i) => <img key={i} src={l.dataURL} alt={l.label || ''} />)}</div>}
        <table>
          <tbody>
            <tr><td class="t1" style={{ background: m.colors.primary, border: 0 }}>{m.title}</td></tr>
            {m.subtitle && <tr><td class="t2" style={{ background: m.colors.accent, border: 0 }}>{m.subtitle}</td></tr>}
          </tbody>
        </table>
        {m.header.length > 0 && (
          <table>
            <colgroup><col style={{ width: '15%' }} /><col style={{ width: '40%' }} /><col style={{ width: '15%' }} /><col style={{ width: '30%' }} /></colgroup>
            <tbody>
              {pairs(m.header).map(([a, b], i) => (
                <tr key={i}>
                  <td style={{ background: m.colors.head, color: m.colors.headText, fontWeight: 700 }}>{a.label}</td><td>{a.value}</td>
                  <td style={{ background: b ? m.colors.head : undefined, color: m.colors.headText, fontWeight: 700 }}>{b?.label}</td><td>{b?.value}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        {m.sections.map((s) => {
          const tw = s.columns.reduce((a, c) => a + (c.w || 10), 0);
          return (
            <table key={s.key}>
              <colgroup>{s.columns.map((c) => <col key={c.key} style={{ width: `${((c.w || 10) / tw) * 100}%` }} />)}</colgroup>
              <thead>
                <tr><th colSpan={s.columns.length} class="band" style={{ background: s.accent ? m.colors.accent : m.colors.primary }}>{s.title}</th></tr>
                <tr>{s.columns.map((c) => <th key={c.key} style={{ background: m.colors.head, color: m.colors.headText }}>{c.label}</th>)}</tr>
              </thead>
              <tbody>
                {s.rows.map((r, i) => r.type === 'group'
                  ? <tr key={i}><td colSpan={s.columns.length} style={{ background: r.fill, color: r.color, fontWeight: 700 }}>{r.label}</td></tr>
                  : <tr key={i}>{r.cells.map((c, j) => <td key={j} class={['num', 'ratio', 'pct', 'sum', 'sr'].includes(c.col.type) || c.col.key === 'unit' ? 'c' : ''} style={{ background: c.fill || (r.type === 'total' && c.text === 'TOTAL' ? '#F2F2F2' : undefined), color: c.color, fontWeight: c.bold || r.type === 'total' ? 700 : undefined }}>{c.text}</td>)}</tr>)}
                {!s.rows.length && <tr><td colSpan={s.columns.length} style={{ color: '#999', textAlign: 'center' }}>No entries</td></tr>}
              </tbody>
            </table>
          );
        })}
        {m.notes && <table><tbody><tr><th class="band" style={{ background: m.colors.primary }}>{m.notes.title}</th></tr><tr><td style={{ whiteSpace: 'pre-wrap' }}>{m.notes.text}</td></tr></tbody></table>}
        {m.photos.length > 0 && (
          <>
            <table><tbody><tr><th class="band" style={{ background: m.colors.primary }}>{m.photoTitle}</th></tr></tbody></table>
            <div class="photos" style={{ gridTemplateColumns: `repeat(${m.photosPerRow}, 1fr)` }}>
              {m.photos.map((p, i) => <figure key={i}><div class="box"><img src={p.url} alt="" /></div>{m.photoCaptions && <figcaption>{p.caption || `Photo ${i + 1}`}</figcaption>}</figure>)}
            </div>
          </>
        )}
        {m.signatures.length > 0 && <div class="sigs">{m.signatures.map((s, i) => <div key={i}>{s}</div>)}</div>}
        {m.showGeneratedBy && <div style={{ color: '#999', fontSize: 9, marginTop: 10 }}>Generated by {APP_NAME}</div>}
      </div>
    </div>
  );
}
function pairs(list) { const out = []; for (let i = 0; i < list.length; i += 2) out.push([list[i], list[i + 1]]); return out; }
