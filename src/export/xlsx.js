// Excel renderer – one sheet per report in the same layout as the original tracker
// (title bands, header block, colour-coded sections, live formulas, photos embedded in a grid).
import ExcelJS from 'exceljs';
import { APP_NAME } from '../defaults.js';
import { fmtDate } from '../utils.js';

const argb = (hex) => 'FF' + String(hex || '#FFFFFF').replace('#', '').toUpperCase().padEnd(6, '0').slice(0, 6);
const fill = (hex) => ({ type: 'pattern', pattern: 'solid', fgColor: { argb: argb(hex) } });
const thin = { style: 'thin', color: { argb: 'FFBFBFBF' } };
const BORDER = { top: thin, left: thin, bottom: thin, right: thin };
const FONT = 'Calibri';

function colLetter(n) { // 1-based
  let s = ''; while (n > 0) { const m = (n - 1) % 26; s = String.fromCharCode(65 + m) + s; n = Math.floor((n - 1) / 26); } return s;
}

function safeSheetName(name, used) {
  let base = String(name).replace(/[\\/?*[\]:]/g, '-').slice(0, 31) || 'Sheet';
  let n = base; let i = 2;
  while (used.has(n.toLowerCase())) { const suf = ` (${i++})`; n = base.slice(0, 31 - suf.length) + suf; }
  used.add(n.toLowerCase());
  return n;
}

export function addReportSheet(wb, model, sheetName) {
  const landscape = model.orientation === 'landscape';
  const ws = wb.addWorksheet(sheetName, {
    pageSetup: { paperSize: 9, orientation: landscape ? 'landscape' : 'portrait', fitToPage: true, fitToWidth: 1, fitToHeight: 0, horizontalCentered: true,
      margins: { left: 0.25, right: 0.25, top: 0.3, bottom: 0.4, header: 0.2, footer: 0.2 } },
    views: [{ showGridLines: false }],
    headerFooter: { oddFooter: `&L&8${model.showGeneratedBy ? 'Generated by ' + APP_NAME : ''}&R&8Page &P of &N` },
  });
  // grid width = widest section
  const widest = model.sections.reduce((a, s) => (s.columns.length > a.columns.length ? s : a), { columns: [] });
  const N = Math.max(8, widest.columns.length);
  const baseW = widest.columns.length ? widest.columns.map((c) => c.w || 10) : Array(N).fill(12);
  while (baseW.length < N) baseW.push(10);
  const scale = 150 / baseW.reduce((a, b) => a + b, 0);
  const widths = baseW.map((w) => Math.max(5, Math.round(w * scale * 10) / 10));
  ws.columns = widths.map((w) => ({ width: w }));
  const colPx = widths.map((w) => Math.round(w * 7 + 5));
  const totalPx = colPx.reduce((a, b) => a + b, 0);

  let r = 1;
  const mergeRow = (row, c1, c2) => { if (c2 > c1) ws.mergeCells(row, c1, row, c2); };
  const styleRange = (row, c1, c2, fn) => { for (let c = c1; c <= c2; c++) fn(ws.getCell(row, c)); };

  // ---- logos ----
  if (model.logos.length) {
    ws.getRow(r).height = 48;
    const hPx = 56;
    const items = model.logos.map((l) => ({ ...l, w: Math.min(200, Math.round(hPx * (l.width / l.height || 1))) }));
    const totalLogos = items.reduce((s, i) => s + i.w, 0);
    const space = items.length > 1 ? (totalPx - totalLogos - 10) / (items.length - 1) : 0;
    let x = 4;
    for (const it of items) {
      const id = wb.addImage({ base64: it.dataURL.split(',')[1], extension: 'png' });
      ws.addImage(id, { tl: pxToCol(colPx, x, r - 1 + 0.08), ext: { width: it.w, height: hPx } });
      x += it.w + Math.max(10, space);
    }
    r++;
  }

  // ---- title ----
  mergeRow(r, 1, N);
  Object.assign(ws.getCell(r, 1), { value: model.title });
  styleRange(r, 1, N, (c) => { c.fill = fill(model.colors.primary); c.font = { name: FONT, size: 16, bold: true, color: { argb: 'FFFFFFFF' } }; c.alignment = { horizontal: 'center', vertical: 'middle' }; });
  ws.getRow(r).height = 28; r++;
  if (model.subtitle) {
    mergeRow(r, 1, N);
    ws.getCell(r, 1).value = model.subtitle;
    styleRange(r, 1, N, (c) => { c.fill = fill(model.colors.accent); c.font = { name: FONT, size: 11, bold: true, color: { argb: 'FFFFFFFF' } }; c.alignment = { horizontal: 'center', vertical: 'middle' }; });
    ws.getRow(r).height = 20; r++;
  }

  // ---- header block ----
  const m = Math.max(3, Math.floor(N * 0.6));
  const blocks = [[1, 2], [3, m], [m + 1, m + 1], [m + 2, N]];
  for (let i = 0; i < model.header.length; i += 2) {
    const pair = [model.header[i], model.header[i + 1]];
    pair.forEach((h, k) => {
      const [l1, l2] = blocks[k * 2]; const [v1, v2] = blocks[k * 2 + 1];
      mergeRow(r, l1, l2); mergeRow(r, v1, v2);
      ws.getCell(r, l1).value = h ? h.label : '';
      ws.getCell(r, v1).value = h ? h.value : '';
      styleRange(r, l1, l2, (c) => { c.fill = fill(h ? model.colors.head : '#FFFFFF'); c.font = { name: FONT, size: 10, bold: true, color: { argb: argb(model.colors.headText) } }; c.border = BORDER; c.alignment = { vertical: 'middle' }; });
      styleRange(r, v1, v2, (c) => { c.font = { name: FONT, size: 10 }; c.border = BORDER; c.alignment = { vertical: 'middle', wrapText: true }; });
    });
    ws.getRow(r).height = 18; r++;
  }
  r++;

  // ---- sections ----
  for (const sec of model.sections) {
    const n = sec.columns.length;
    // map section column i -> [startCol, endCol] (last column stretches to N)
    const span = sec.columns.map((_, i) => (i < n - 1 ? [i + 1, i + 1] : [i + 1, N]));
    mergeRow(r, 1, N);
    ws.getCell(r, 1).value = sec.title;
    styleRange(r, 1, N, (c) => { c.fill = fill(sec.accent ? model.colors.accent : model.colors.primary); c.font = { name: FONT, size: 11, bold: true, color: { argb: 'FFFFFFFF' } }; c.alignment = { vertical: 'middle' }; });
    ws.getRow(r).height = 20; r++;
    // header row
    sec.columns.forEach((c, i) => {
      const [a, b] = span[i]; mergeRow(r, a, b);
      ws.getCell(r, a).value = c.label;
      styleRange(r, a, b, (cell) => { cell.fill = fill(model.colors.head); cell.font = { name: FONT, size: 10, bold: true, color: { argb: argb(model.colors.headText) } }; cell.border = BORDER; cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true }; });
    });
    ws.getRow(r).height = 30; r++;
    const firstDataRowOfGroup = { v: r };
    let groupDataRows = [];
    for (const row of sec.rows) {
      if (row.type === 'group') {
        mergeRow(r, 1, N);
        ws.getCell(r, 1).value = '   ' + row.label;
        styleRange(r, 1, N, (c) => { c.fill = fill(row.fill || '#EEEEEE'); c.font = { name: FONT, size: 10, bold: true, color: { argb: argb(row.color || '#333333') } }; c.border = BORDER; });
        r++; groupDataRows = []; firstDataRowOfGroup.v = r; continue;
      }
      const colIdx = (key) => { const i = sec.columns.findIndex((c) => c.key === key); return i < 0 ? null : span[i][0]; };
      row.cells.forEach((cell, i) => {
        const c = cell.col; const [a, b] = span[i]; mergeRow(r, a, b);
        const target = ws.getCell(r, a);
        let value = cell.text;
        let numFmt;
        if (row.type === 'total' && ['num', 'sum'].includes(c.type) && cell.v != null && groupDataRows.length) {
          const L = colLetter(a); value = { formula: `SUM(${L}${groupDataRows[0]}:${L}${groupDataRows[groupDataRows.length - 1]})`, result: cell.v };
          numFmt = '0';
        } else if (row.type === 'data' && c.type === 'sr') { value = cell.v; }
        else if (row.type === 'data' && c.type === 'num' && cell.v != null) { value = cell.v; numFmt = ['target', 'achieved'].includes(c.key) ? '0.00' : 'General'; }
        else if (row.type === 'data' && c.type === 'pct' && cell.v != null) { value = cell.v; numFmt = '0%'; }
        else if (row.type === 'data' && c.type === 'ratio') {
          const ni = colIdx(c.num), di = colIdx(c.den);
          if (ni && di) { const NL = colLetter(ni) + r, DL = colLetter(di) + r; value = { formula: `IF(OR(${DL}="",${NL}=""),"",IF(${DL}=0,IF(${NL}>0,1,0),${NL}/${DL}))`, result: cell.v == null ? '' : cell.v }; }
          else value = cell.v;
          numFmt = '0%';
        } else if (row.type === 'data' && c.type === 'sum') {
          const cols = c.of.map(colIdx).filter(Boolean);
          if (cols.length) value = { formula: `IF(COUNT(${cols.map((x) => colLetter(x) + r).join(',')})=0,"",SUM(${cols.map((x) => colLetter(x) + r).join(',')}))`, result: cell.v == null ? '' : cell.v };
          numFmt = '0';
        }
        target.value = value === '' ? null : value;
        styleRange(r, a, b, (x) => {
          x.border = BORDER;
          x.font = { name: FONT, size: 10, bold: !!(cell.bold || row.type === 'total'), color: cell.color ? { argb: argb(cell.color) } : undefined };
          if (cell.fill) x.fill = fill(cell.fill);
          x.alignment = { vertical: 'middle', wrapText: true, horizontal: ['num', 'ratio', 'pct', 'sum', 'sr'].includes(c.type) || c.key === 'unit' || c.key === 'responsible' ? 'center' : 'left' };
          if (numFmt) x.numFmt = numFmt;
        });
      });
      // auto row height for long text
      const longest = Math.max(...row.cells.map((cell, i) => { const [a, b] = span[i]; let w = 0; for (let k = a; k <= b; k++) w += widths[k - 1]; return Math.ceil(String(cell.text || '').length / Math.max(4, w * 1.1)); }));
      ws.getRow(r).height = Math.max(17, 15 * longest + 3);
      if (row.type === 'data') groupDataRows.push(r);
      r++;
    }
    // live conditional colours (so they update when edited in Excel)
    sec.columns.forEach((c, i) => {
      if (!c.colorScale) return;
      const L = colLetter(span[i][0]);
      const ref = `${L}${firstDataRowOfGroupStart(sec, r)}:${L}${r - 1}`;
      if (c.colorScale === 'status') {
        const tl = `${L}${firstDataRowOfGroupStart(sec, r)}`;
        const rule = (expr, bg, fg, priority) => ({ type: 'expression', formulae: [expr], priority, style: { fill: { type: 'pattern', pattern: 'solid', bgColor: { argb: bg } }, font: { color: { argb: fg } } } });
        ws.addConditionalFormatting({ ref, rules: [
          rule(`AND(ISNUMBER(${tl}),${tl}>=1)`, 'FFC6EFCE', 'FF006100', 1),
          rule(`AND(ISNUMBER(${tl}),${tl}>=0.7,${tl}<1)`, 'FFFFEB9C', 'FF9C5700', 2),
          rule(`AND(ISNUMBER(${tl}),${tl}<0.7)`, 'FFFFC7CE', 'FF9C0006', 3),
        ] });
      } else {
        ws.addConditionalFormatting({ ref, rules: [{ type: 'colorScale', priority: 4, cfvo: [{ type: 'num', value: 0 }, { type: 'num', value: 0.5 }, { type: 'num', value: 1 }], color: [{ argb: 'FFF8696B' }, { argb: 'FFFFEB84' }, { argb: 'FF63BE7B' }] }] });
      }
    });
    r++;
  }

  // ---- notes ----
  if (model.notes) {
    mergeRow(r, 1, N); ws.getCell(r, 1).value = model.notes.title;
    styleRange(r, 1, N, (c) => { c.fill = fill(model.colors.primary); c.font = { name: FONT, size: 11, bold: true, color: { argb: 'FFFFFFFF' } }; });
    r++;
    mergeRow(r, 1, N); ws.getCell(r, 1).value = model.notes.text;
    styleRange(r, 1, N, (c) => { c.border = BORDER; c.alignment = { wrapText: true, vertical: 'top' }; c.font = { name: FONT, size: 10 }; });
    ws.getRow(r).height = Math.max(20, 15 * Math.ceil(model.notes.text.length / 140) + 15 * (model.notes.text.split('\n').length - 1));
    r += 2;
  }

  // ---- photos ----
  if (model.photos.length) {
    mergeRow(r, 1, N); ws.getCell(r, 1).value = model.photoTitle;
    styleRange(r, 1, N, (c) => { c.fill = fill(model.colors.primary); c.font = { name: FONT, size: 11, bold: true, color: { argb: 'FFFFFFFF' } }; });
    ws.getRow(r).height = 20; r++;
    const per = model.photosPerRow; const gap = 8;
    const slot = (totalPx - gap * (per - 1)) / per;
    const boxH = Math.round(slot * 0.75);
    for (let i = 0; i < model.photos.length; i += per) {
      ws.getRow(r).height = boxH * 0.75 + 6; // points
      model.photos.slice(i, i + per).forEach((p, j) => {
        const ratio = p.width / p.height || 1.333;
        let w = slot, h = slot / ratio; if (h > boxH) { h = boxH; w = boxH * ratio; }
        const x = j * (slot + gap) + (slot - w) / 2;
        const id = wb.addImage({ buffer: p.data, extension: 'jpeg' });
        ws.addImage(id, { tl: pxToCol(colPx, x, r - 1 + (boxH - h) / 2 / (boxH + 8)), ext: { width: Math.round(w), height: Math.round(h) } });
      });
      r++;
      if (model.photoCaptions) {
        const slotsCols = slotColumns(colPx, per, gap);
        model.photos.slice(i, i + per).forEach((p, j) => {
          const [a, b] = slotsCols[j];
          if (b > a) ws.mergeCells(r, a, r, b);
          ws.getCell(r, a).value = p.caption || `Photo ${i + j + 1}`;
          ws.getCell(r, a).alignment = { horizontal: 'center', vertical: 'top', wrapText: true };
          ws.getCell(r, a).font = { name: FONT, size: 9, italic: true };
        });
        ws.getRow(r).height = 26; r++;
      }
    }
    r++;
  }

  // ---- signatures ----
  if (model.signatures.length) {
    r += 2;
    const k = model.signatures.length; const each = Math.floor(N / k);
    model.signatures.forEach((s, i) => {
      const a = i * each + 1; const b = i === k - 1 ? N : (i + 1) * each;
      if (b > a) ws.mergeCells(r, a, r, b);
      const c = ws.getCell(r, a); c.value = s; c.font = { name: FONT, size: 10, bold: true }; c.alignment = { horizontal: 'center' };
      for (let x = a; x <= b; x++) ws.getCell(r, x).border = { top: { style: 'thin', color: { argb: 'FF555555' } } };
    });
    r++;
  }
  ws.pageSetup.printArea = `A1:${colLetter(N)}${r}`;
  return ws;
}

function firstDataRowOfGroupStart(sec, endRow) {
  // rows of this section occupy the last sec.rows.length rows before endRow
  return endRow - sec.rows.length;
}

function pxToCol(colPx, x, rowFloat) {
  let acc = 0;
  for (let i = 0; i < colPx.length; i++) {
    if (x < acc + colPx[i]) return { col: i + (x - acc) / colPx[i], row: rowFloat };
    acc += colPx[i];
  }
  return { col: colPx.length - 1, row: rowFloat };
}
function slotColumns(colPx, per, gap) {
  const total = colPx.reduce((a, b) => a + b, 0);
  const slot = (total - gap * (per - 1)) / per;
  const out = [];
  for (let j = 0; j < per; j++) {
    const x1 = j * (slot + gap), x2 = x1 + slot;
    let a = null, b = null, acc = 0;
    for (let i = 0; i < colPx.length; i++) {
      const mid = acc + colPx[i] / 2;
      if (mid >= x1 && mid <= x2) { if (a === null) a = i + 1; b = i + 1; }
      acc += colPx[i];
    }
    if (a === null) { a = Math.min(colPx.length, j + 1); b = a; }
    out.push([a, b]);
  }
  // make spans disjoint
  for (let j = 1; j < out.length; j++) if (out[j][0] <= out[j - 1][1]) out[j][0] = out[j - 1][1] + 1;
  for (const s of out) if (s[1] < s[0]) s[1] = s[0];
  return out;
}

/** Summary sheets for period exports */
function addSummarySheets(wb, summary, used, colors) {
  const head = (ws, row, labels) => {
    labels.forEach((l, i) => { const c = ws.getCell(row, i + 1); c.value = l; c.fill = fill(colors.head); c.font = { name: FONT, bold: true, color: { argb: argb(colors.headText) } }; c.border = BORDER; c.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true }; });
    ws.getRow(row).height = 30;
  };
  const band = (ws, row, text, n) => { ws.mergeCells(row, 1, row, n); const c = ws.getCell(row, 1); c.value = text; c.fill = fill(colors.primary); c.font = { name: FONT, size: 13, bold: true, color: { argb: 'FFFFFFFF' } }; ws.getRow(row).height = 24; };
  // Summary
  const s = wb.addWorksheet(safeSheetName('Summary', used), { views: [{ showGridLines: false }] });
  s.columns = [{ width: 34 }, { width: 18 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 16 }];
  band(s, 1, `${summary.projectName} – Summary ${summary.rangeLabel}`, 8);
  const k = summary.data;
  const kpis = [['Reports filed', k.reportDays], ['Total man-days', k.totalManDays], ['Average manpower / day', Math.round(k.avgManpower * 10) / 10], ['Peak manpower', `${k.peak.value}${k.peak.date ? ' on ' + fmtDate(k.peak.date, { weekday: false }) : ''}`],
    ['Targets set', k.targets.total], ['Targets achieved', k.targets.achieved], ['Partially achieved', k.targets.partial], ['Not achieved', k.targets.failed], ['Success rate', k.targets.success == null ? '' : k.targets.success], ['Site photos', k.photos]];
  kpis.forEach(([l, v], i) => { const row = 3 + i; s.getCell(row, 1).value = l; s.getCell(row, 2).value = v; s.getCell(row, 1).font = { name: FONT, bold: true }; s.getCell(row, 1).border = BORDER; s.getCell(row, 2).border = BORDER; if (l === 'Success rate') s.getCell(row, 2).numFmt = '0%'; });
  let r = 15;
  band(s, r, 'WORK LIST & TARGET SUMMARY', 8); r++;
  head(s, r, ['Work Particulars', 'Unit', 'Total Targets', 'Achieved', 'Partial', 'Failed', 'Success %', 'Latest Completion %']); r++;
  for (const w of k.works) {
    [w.name, w.unit, w.targets, w.achieved, w.partial, w.failed, w.success == null ? '' : w.success, w.latestPct == null ? '' : w.latestPct / 100].forEach((v, i) => { const c = s.getCell(r, i + 1); c.value = v; c.border = BORDER; if (i >= 6) c.numFmt = '0%'; });
    r++;
  }
  r++;
  band(s, r, 'MANPOWER BY PERIOD', 8); r++;
  head(s, r, ['Period', 'Report days', 'Man-days', 'Avg / day', ...k.contractors.slice(0, 4)]); r++;
  for (const b of k.series) {
    [b.label, b.days, b.manpower, Math.round(b.avgManpower * 10) / 10, ...k.contractors.slice(0, 4).map((c) => b.byContractor[c] || 0)].forEach((v, i) => { const c = s.getCell(r, i + 1); c.value = v; c.border = BORDER; });
    r++;
  }
  // Target log
  const t = wb.addWorksheet(safeSheetName('Target Log', used), { views: [{ state: 'frozen', ySplit: 1 }] });
  t.columns = [{ width: 13 }, { width: 34 }, { width: 18 }, { width: 10 }, { width: 11 }, { width: 11 }, { width: 11 }, { width: 12 }, { width: 30 }];
  head(t, 1, ['Date', 'Work Particulars', 'Location', 'Unit', 'Target Qty', 'Achieved Qty', '% Achieved', 'Status', 'Remarks']);
  k.targetLog.forEach((e, i) => {
    const row = i + 2;
    [fmtDate(e.date, { weekday: false }), e.work, e.location, e.unit, e.target, e.achievedQty, e.ratio, e.status, e.remarks].forEach((v, j) => { const c = t.getCell(row, j + 1); c.value = v; c.border = BORDER; if (j === 6) c.numFmt = '0%'; });
    const st = t.getCell(row, 8); st.fill = fill(e.status === 'Achieved' ? '#C6EFCE' : e.status === 'Partial' ? '#FFEB9C' : '#FFC7CE');
  });
  t.autoFilter = { from: 'A1', to: 'I1' };
  // Manpower log
  const mp = wb.addWorksheet(safeSheetName('Manpower Log', used), { views: [{ state: 'frozen', ySplit: 1 }] });
  mp.columns = [{ width: 13 }, { width: 30 }, { width: 11 }, { width: 12 }, { width: 11 }, { width: 12 }, { width: 10 }];
  head(mp, 1, ['Date', 'Contractor', 'Skilled', 'Semi-Skilled', 'Unskilled', 'Supervisors', 'Total']);
  k.manpowerLog.forEach((e, i) => {
    [fmtDate(e.date, { weekday: false }), e.contractor, e.skilled, e.semi, e.unskilled, e.supervisors, e.total].forEach((v, j) => { const c = mp.getCell(i + 2, j + 1); c.value = v; c.border = BORDER; });
  });
  mp.autoFilter = { from: 'A1', to: 'G1' };
}

/**
 * @param {Array<{model, sheetName}>} sheets
 * @param {{summary?:object}} opts
 */
export async function renderXLSX(sheets, opts = {}) {
  const wb = new ExcelJS.Workbook();
  wb.creator = APP_NAME; wb.created = new Date(); wb.modified = new Date();
  const used = new Set();
  if (opts.summary) addSummarySheets(wb, opts.summary, used, sheets[0]?.model.colors || opts.summary.colors);
  for (const s of sheets) addReportSheet(wb, s.model, safeSheetName(s.sheetName, used));
  if (!wb.worksheets.length) wb.addWorksheet('Empty');
  const buf = await wb.xlsx.writeBuffer();
  return new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}
